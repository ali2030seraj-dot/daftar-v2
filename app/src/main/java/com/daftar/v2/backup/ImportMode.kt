package com.daftar.v2.backup

/**
 * طريقة استيراد النسخة الاحتياطية.
 */
enum class ImportMode {
    /**
     * دمج: يُحدّث الموجود ويُضيف الجديد.
     * آمن — لا يحذف البيانات الحالية.
     */
    MERGE,

    /**
     * استبدال: يحذف كل البيانات الحالية ثم يستورد.
     * خطير — يفقد كل ما ليس في النسخة.
     */
    REPLACE
}